let cached: readonly number[] | null = null;

/**
 * 字频表的码位形式，按频率降序、已去重。
 *
 * 使用 Array.from 按码位迭代，正确处理扩展区汉字的代理对。
 */
export function charFreqCodepoints(): readonly number[] {
  if (cached) return cached;
  const seen = new Set<number>();
  const out: number[] = [];
  for (const ch of Array.from(CHAR_FREQ_ZH)) {
    const cp = ch.codePointAt(0);
    if (cp === undefined || seen.has(cp)) continue;
    seen.add(cp);
    out.push(cp);
  }
  cached = out;
  return out;
}
